			array(
				'name'  => $name( 'brand.value' ),
				'label' => __( 'Brand', 'mr-tu-multilang-seo' ),
				'value' => $data['brand']['value'],
				'error' => $err( 'brand.value' ),
			)
		);
		self::verify_toggle( $name( 'brand.verified' ), $data['brand']['verified'] );
		self::group_close();
		self::group_open( __( 'Full shop name', 'mr-tu-multilang-seo' ), $data['display_name']['verified'], $data['display_name']['note'] );
		self::input(
			array(
				'name'  => $name( 'display_name.value' ),
				'label' => __( 'Full shop name (as on Google Maps)', 'mr-tu-multilang-seo' ),
				'value' => $data['display_name']['value'],
				'error' => $err( 'display_name.value' ),
			)
		);
		self::verify_toggle( $name( 'display_name.verified' ), $data['display_name']['verified'] );
		self::group_close();
		Admin::card_close();

		// Address.
		Admin::card_open( __( 'Address', 'mr-tu-multilang-seo' ), __( 'Shown on the website only after you have checked that customers are really received at this address.', 'mr-tu-multilang-seo' ) );
		self::group_open( __( 'Address', 'mr-tu-multilang-seo' ), $data['address']['verified'], $data['address']['note'] );
		echo '<div class="mrtu-grid mrtu-grid--2">';
		$parts = array(
			'street'      => __( 'Street and number', 'mr-tu-multilang-seo' ),
			'ward'        => __( 'Ward', 'mr-tu-multilang-seo' ),
			'city'        => __( 'City', 'mr-tu-multilang-seo' ),
			'postal_code' => __( 'Postal code', 'mr-tu-multilang-seo' ),
