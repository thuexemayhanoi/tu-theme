			self::group_open( $field[0], $data[ $key ]['verified'], $data[ $key ]['note'] );
			self::input(
				array(
					'name'  => $name( $key . '.value' ),
					'label' => $field[0],
					'value' => $data[ $key ]['value'],
					'type'  => $field[1],
					'help'  => $field[2],
					'error' => $err( $key . '.value' ),
				)
			);
			self::verify_toggle( $name( $key . '.verified' ), $data[ $key ]['verified'] );
			self::group_close();
		}
		Admin::card_close();

		// Chat apps.
		Admin::card_open( __( 'Chat apps', 'mr-tu-multilang-seo' ), __( 'Switch a channel on only after you have checked that the app works on this number.', 'mr-tu-multilang-seo' ) );
		foreach ( array(
			'whatsapp' => 'WhatsApp',
			'zalo'     => 'Zalo',
		) as $channel => $label ) {
			$c = $data['channels'][ $channel ];
			self::group_open( $label, $c['verified'], $c['note'] );
			/* translators: %s: chat app name. */
			Admin::toggle( $name( 'channels.' . $channel . '.enabled' ), sprintf( __( 'Show %s on the website', 'mr-tu-multilang-seo' ), $label ), $c['enabled'] );
			self::input(
				array(
					/* translators: %s: chat app name. */
					'label'       => sprintf( __( '%s number', 'mr-tu-multilang-seo' ), $label ),
					'name'        => $name( 'channels.' . $channel . '.value' ),
					'value'       => $c['value'],
					'type'        => 'tel',
					'placeholder' => 'whatsapp' === $channel ? '+84…' : '08…',
					'error'       => $err( 'channels.' . $channel . '.value' ),
				)
			);
			self::verify_toggle( $name( 'channels.' . $channel . '.verified' ), $c['verified'] );
			self::group_close();
		}
		Admin::card_close();

		Admin::save_bar( 'mrtu_save_business' );
		echo '</form>';

		self::render_backup();
		Admin::page_close();
	}

	/**
	 * Verification summary + "Mark all verified".
	 *
	 * @param array $b Stored record.
	 */
	private static function render_summary( $b ) {
		$facts   = array(
			'brand'         => __( 'Brand', 'mr-tu-multilang-seo' ),
			'display_name'  => __( 'Full shop name', 'mr-tu-multilang-seo' ),
			'address'       => __( 'Address', 'mr-tu-multilang-seo' ),
			'phone'         => __( 'Phone number', 'mr-tu-multilang-seo' ),
			'hours'         => __( 'Opening hours', 'mr-tu-multilang-seo' ),
			'service_model' => __( 'Service model', 'mr-tu-multilang-seo' ),
			'service_area'  => __( 'Service area', 'mr-tu-multilang-seo' ),
			'maps_url'      => __( 'Google Maps link', 'mr-tu-multilang-seo' ),
			'email'         => __( 'Public email', 'mr-tu-multilang-seo' ),
			'website'       => __( 'Website', 'mr-tu-multilang-seo' ),
		);
		$pending = array();
		foreach ( $facts as $key => $label ) {
			if ( empty( $b[ $key ]['verified'] ) ) {
				$pending[] = $label;
			}
		}
		$done = count( $facts ) - count( $pending );
		Admin::card_open( __( 'Verification', 'mr-tu-multilang-seo' ) );
		/* translators: 1: number of verified details, 2: total number of details. */
		echo '<p class="mrtu-summary"><strong>' . esc_html( sprintf( __( '%1$d of %2$d details verified', 'mr-tu-multilang-seo' ), $done, count( $facts ) ) ) . '</strong></p>';
		if ( $pending ) {
			echo '<p class="mrtu-card__help">' . esc_html__( 'Still PENDING VERIFICATION (hidden on the website):', 'mr-tu-multilang-seo' ) . ' ' . esc_html( implode( ', ', $pending ) ) . '</p>';
