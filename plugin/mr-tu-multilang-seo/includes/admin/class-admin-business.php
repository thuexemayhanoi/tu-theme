	/**
	 * Saves the NAP form.
	 */
	public static function handle_save() {
		Admin::verify_request( 'mrtu_save_business' );
		// phpcs:disable WordPress.Security.NonceVerification.Missing -- nonce + capability verified by Admin::verify_request() above.
		// phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized -- every field is sanitised and validated in Business::normalize_business().
		$input      = isset( $_POST['business'] ) && is_array( $_POST['business'] ) ? wp_unslash( $_POST['business'] ) : array();
		$verify_all = ! empty( $_POST['mrtu_verify_all'] );
		// phpcs:enable WordPress.Security.NonceVerification.Missing
		$input = self::merge_notes( $input, Business::get_business() );
		if ( ! isset( $input['hours']['days'] ) ) {
			$input['hours']['days'] = array();
		}
		if ( $verify_all ) {
			$input = Business::mark_all_verified( $input );
		}
		$result = Business::save_business( $input );
		$url    = Admin::url( self::SLUG );
		if ( is_wp_error( $result ) ) {
			$data = $result->get_error_data();
			self::remember( 'business', $data['data'], $data['errors'] );
			Admin::redirect_with_notice( $url, __( 'Nothing was saved. Please fix the highlighted fields.', 'mr-tu-multilang-seo' ), 'error' );
		}
		if ( 'unchanged' === $result ) {
			Admin::redirect_with_notice( $url, __( 'No changes to save.', 'mr-tu-multilang-seo' ), 'info' );
		}
		Admin::redirect_with_notice( $url, $verify_all ? __( 'Saved. Every filled-in detail is now marked as verified.', 'mr-tu-multilang-seo' ) : __( 'Store information saved. The website is updated in all languages.', 'mr-tu-multilang-seo' ) );
	}

	/**
	 * Keeps the admin notes (not editable in the form) when the form is saved.
	 *
	 * @param array $input  Submitted data.
	 * @param array $stored Stored record.
	 * @return array
	 */
	private static function merge_notes( $input, $stored ) {
		foreach ( $stored as $key => $record ) {
			if ( is_array( $record ) && isset( $record['note'] ) && isset( $input[ $key ] ) && is_array( $input[ $key ] ) && ! isset( $input[ $key ]['note'] ) ) {
				$input[ $key ]['note'] = $record['note'];
			}
		}
		foreach ( array( 'whatsapp', 'zalo' ) as $channel ) {
			if ( isset( $input['channels'][ $channel ] ) && is_array( $input['channels'][ $channel ] ) && ! isset( $input['channels'][ $channel ]['note'] ) ) {
				$input['channels'][ $channel ]['note'] = $stored['channels'][ $channel ]['note'];
			}
		}
		return $input;
	}

	/**
	 * Streams the JSON backup.
	 */
	public static function handle_export() {
		Admin::verify_request( 'mrtu_business_export' );
		$json     = Business::export_json();
		$filename = 'mrtu-business-' . gmdate( 'Ymd-His' ) . '.json';
		nocache_headers();
		header( 'Content-Type: application/json; charset=utf-8' );
		header( 'Content-Disposition: attachment; filename="' . $filename . '"' );
		header( 'X-Content-Type-Options: nosniff' );
		header( 'Content-Length: ' . strlen( $json ) );
		echo $json; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- JSON download, not HTML.
		exit;
	}

	/**
	 * Imports an uploaded JSON backup.
	 */
	public static function handle_import() {
		Admin::verify_request( 'mrtu_business_import' );
		$url = Admin::url( self::SLUG ) . '#mrtu-backup';
		// phpcs:disable WordPress.Security.NonceVerification.Missing -- nonce + capability verified by Admin::verify_request() above.
		$file = isset( $_FILES['mrtu_import_file'] ) && is_array( $_FILES['mrtu_import_file'] ) ? $_FILES['mrtu_import_file'] : array(); // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized -- checked field by field below.
		// phpcs:enable WordPress.Security.NonceVerification.Missing
		$err  = isset( $file['error'] ) ? (int) $file['error'] : UPLOAD_ERR_NO_FILE;
		$tmp  = isset( $file['tmp_name'] ) ? (string) $file['tmp_name'] : '';
		$size = isset( $file['size'] ) ? (int) $file['size'] : 0;
		$name = isset( $file['name'] ) ? sanitize_file_name( wp_unslash( $file['name'] ) ) : '';

		if ( UPLOAD_ERR_OK !== $err || '' === $tmp || ! is_uploaded_file( $tmp ) ) {
			Admin::redirect_with_notice( $url, __( 'Please choose a backup file to import.', 'mr-tu-multilang-seo' ), 'error' );
		}
		if ( $size > Business::IMPORT_MAX_BYTES || filesize( $tmp ) > Business::IMPORT_MAX_BYTES ) {
			Admin::redirect_with_notice( $url, __( 'The file is larger than 200 KB.', 'mr-tu-multilang-seo' ), 'error' );
		}
		if ( '' !== $name && 'json' !== strtolower( pathinfo( $name, PATHINFO_EXTENSION ) ) ) {
			Admin::redirect_with_notice( $url, __( 'Please choose a .json backup file.', 'mr-tu-multilang-seo' ), 'error' );
		}
		$json   = file_get_contents( $tmp ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- local uploaded temp file.
		$result = Business::import_json( is_string( $json ) ? $json : '' );
		if ( is_wp_error( $result ) ) {
			$message = $result->get_error_message();
			$data    = $result->get_error_data();
			if ( is_array( $data ) && ! empty( $data['errors'] ) ) {
				$details  = array_slice( array_values( $data['errors'] ), 0, 3 );
				$message .= ' ' . implode( ' ', $details );
			}
			Admin::redirect_with_notice( $url, $message, 'error' );
		}
		Admin::redirect_with_notice( $url, __( 'Backup imported. The previous data was saved in the history below.', 'mr-tu-multilang-seo' ) );
	}

	/**
	 * Restores a snapshot.
	 */
	public static function handle_restore() {
		Admin::verify_request( 'mrtu_business_restore' );
		$id     = isset( $_POST['snapshot'] ) ? sanitize_key( wp_unslash( $_POST['snapshot'] ) ) : ''; // phpcs:ignore WordPress.Security.NonceVerification.Missing -- verified by Admin::verify_request().
		$result = Business::restore( $id );
		$url    = Admin::url( self::SLUG ) . '#mrtu-backup';
		if ( is_wp_error( $result ) ) {
			Admin::redirect_with_notice( $url, $result->get_error_message(), 'error' );
		}
		Admin::redirect_with_notice( $url, __( 'Backup restored. The data before the restore was saved in the history.', 'mr-tu-multilang-seo' ) );
	}
