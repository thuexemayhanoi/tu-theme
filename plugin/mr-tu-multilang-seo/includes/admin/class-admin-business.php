		$errors = $state ? (array) $state['errors'] : array();
		$name   = static function ( $path ) {
			return 'business[' . str_replace( '.', '][', $path ) . ']';
		};
		$err    = static function ( $key ) use ( $errors ) {
			return isset( $errors[ $key ] ) ? $errors[ $key ] : '';
		};

		Admin::page_open( __( 'Store information', 'mr-tu-multilang-seo' ), __( 'Name, address, phone and opening hours of Mr Tu. Only details marked as verified appear on the website, in all five languages.', 'mr-tu-multilang-seo' ) );
		echo Admin::last_updated( $stored['updated_at'], $stored['updated_by'] ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- escaped by Admin::last_updated().
		self::error_summary( $errors );
		self::render_summary( $stored );

