<?php
/**
 * Admin screen "Store information" (slug mrtu-business): NAP with per-field verification,
 * "Mark all verified", Backup & restore (export JSON, import JSON, history with restore).
 *
 * Also hosts the small helpers shared by the business admin screens (inline errors,
 * redisplay of submitted values after a validation error, asset loading).
 *
 * @package MrTu\Multilang
 */

namespace MrTu\Multilang\Admin;

use MrTu\Multilang\Business;

defined( 'ABSPATH' ) || exit;

/**
 * Store information screen.
 */
final class Admin_Business {

	const SLUG    = 'mrtu-business';
	const SCREENS = array( 'mrtu-business', 'mrtu-pricing', 'mrtu-vehicles', 'mrtu-quick-contact' );

	/**
	 * Wires hooks.
	 */
	public static function init() {
		add_filter( 'mrtu_admin_pages', array( __CLASS__, 'register_page' ) );
		add_action( 'admin_enqueue_scripts', array( __CLASS__, 'enqueue' ) );
		add_action( 'admin_post_mrtu_save_business', array( __CLASS__, 'handle_save' ) );
		add_action( 'admin_post_mrtu_business_export', array( __CLASS__, 'handle_export' ) );
		add_action( 'admin_post_mrtu_business_import', array( __CLASS__, 'handle_import' ) );
		add_action( 'admin_post_mrtu_business_restore', array( __CLASS__, 'handle_restore' ) );
	}

	/**
	 * Registers the screen.
	 *
	 * @param array $pages Pages.
	 * @return array
	 */
	public static function register_page( $pages ) {
		$pages[] = array(
			'slug'       => self::SLUG,
			'title'      => __( 'Store information', 'mr-tu-multilang-seo' ),
			'menu_title' => __( 'Store info', 'mr-tu-multilang-seo' ),
			'capability' => 'manage_options',
			'callback'   => array( __CLASS__, 'render' ),
			'position'   => 10,
		);
		return $pages;
	}

	/*
	 * Shared helpers for the business admin screens
	 * ------------------------------------------------------------------
	 */

	/**
	 * Current admin page slug (read-only routing).
	 *
	 * @return string
	 */
	public static function current_page() {
		// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- read-only screen routing.
		return isset( $_GET['page'] ) ? sanitize_key( wp_unslash( $_GET['page'] ) ) : '';
	}

	/**
	 * Enqueues the shared business admin assets on our four screens.
	 */
	public static function enqueue() {
		if ( ! in_array( self::current_page(), self::SCREENS, true ) ) {
			return;
		}
		wp_enqueue_style( 'mrtu-admin-business', MRTU_ML_URL . 'assets/admin/business.css', array(), MRTU_ML_VERSION );
		wp_enqueue_script( 'mrtu-admin-business', MRTU_ML_URL . 'assets/admin/business.js', array(), MRTU_ML_VERSION, true );
	}

	/**
	 * Remembers submitted values + errors for redisplay after a redirect (no data loss).
	 *
	 * @param string $screen Screen key.
	 * @param array  $data   Submitted (sanitised) data.
	 * @param array  $errors Errors.
	 */
	public static function remember( $screen, $data, $errors ) {
		set_transient(
			'mrtu_form_' . $screen . '_' . get_current_user_id(),
			array(
				'data'   => $data,
				'errors' => $errors,
			),
			15 * MINUTE_IN_SECONDS
		);
	}

	/**
	 * Returns (and forgets) remembered form state.
	 *
	 * @param string $screen Screen key.
	 * @return array|null [ data, errors ]
	 */
	public static function recall( $screen ) {
		$key   = 'mrtu_form_' . $screen . '_' . get_current_user_id();
		$state = get_transient( $key );
		if ( false === $state ) {
			return null;
		}
		delete_transient( $key );
		return ( is_array( $state ) && isset( $state['data'], $state['errors'] ) ) ? $state : null;
	}

	/**
	 * Element id generated by Admin::field() for an input name.
	 *
	 * @param string $name Input name.
	 * @return string
	 */
	public static function field_id( $name ) {
		return 'mrtu-' . sanitize_html_class( str_replace( array( '[', ']' ), '-', $name ) );
	}

	/**
	 * Admin::field() wrapper with inline error (aria-invalid + aria-describedby).
	 *
	 * @param array $args Admin::field args + 'error' (message).
	 */
	public static function input( $args ) {
		$error = isset( $args['error'] ) ? (string) $args['error'] : '';
		unset( $args['error'] );
		$args['attrs'] = isset( $args['attrs'] ) ? (array) $args['attrs'] : array();
		$id            = self::field_id( $args['name'] );
		if ( '' !== $error ) {
			$args['attrs']['aria-invalid']     = 'true';
			$args['attrs']['aria-describedby'] = $id . '-error';
			echo '<div class="mrtu-has-error">';
		}
		Admin::field( $args );
		if ( '' !== $error ) {
			echo '<p class="mrtu-field__error" id="' . esc_attr( $id . '-error' ) . '">' . esc_html( $error ) . '</p></div>';
		}
	}

	/**
	 * Prints an inline error for a key when present.
	 *
	 * @param array  $errors Errors.
	 * @param string $key    Error key.
	 */
	public static function error( $errors, $key ) {
		if ( isset( $errors[ $key ] ) ) {
			echo '<p class="mrtu-field__error" role="alert">' . esc_html( $errors[ $key ] ) . '</p>';
		}
	}

	/**
	 * Error summary box listing every problem.
	 *
	 * @param array $errors Errors.
	 */
	public static function error_summary( $errors ) {
		if ( ! $errors ) {
			return;
		}
		echo '<div class="mrtu-error-summary" role="alert"><p><strong>' . esc_html__( 'Please fix these fields:', 'mr-tu-multilang-seo' ) . '</strong></p><ul>';
		foreach ( $errors as $message ) {
			echo '<li>' . esc_html( $message ) . '</li>';
		}
		echo '</ul></div>';
	}

	/**
	 * Verification badge that follows its toggle live (see assets/admin/business.js).
	 *
	 * @param bool $verified State.
	 * @return string Escaped HTML.
	 */
	public static function live_badge( $verified ) {
		return '<span class="mrtu-badge ' . ( $verified ? 'mrtu-badge--ok' : 'mrtu-badge--pending' ) . '" data-mrtu-badge data-ok="' . esc_attr__( 'Verified', 'mr-tu-multilang-seo' ) . '" data-pending="' . esc_attr__( 'PENDING VERIFICATION', 'mr-tu-multilang-seo' ) . '">'
			. esc_html( $verified ? __( 'Verified', 'mr-tu-multilang-seo' ) : __( 'PENDING VERIFICATION', 'mr-tu-multilang-seo' ) ) . '</span>';
	}

	/**
	 * Opens a verification group (fieldset with live badge).
	 *
	 * @param string $title    Legend.
	 * @param bool   $verified State.
	 * @param string $note     Owner/admin note shown while unverified.
	 */
	public static function group_open( $title, $verified, $note = '' ) {
		echo '<fieldset class="mrtu-group" data-mrtu-group>';
		echo '<legend class="mrtu-group__title"><span>' . esc_html( $title ) . '</span> ' . self::live_badge( $verified ) . '</legend>'; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- live_badge() escapes.
		if ( '' !== $note && ! $verified ) {
			/* translators: %s: reminder about what still has to be checked. */
			echo '<p class="mrtu-group__note">' . esc_html( sprintf( __( 'To check: %s', 'mr-tu-multilang-seo' ), $note ) ) . '</p>';
		}
	}

	/**
	 * Closes a verification group.
	 */
	public static function group_close() {
		echo '</fieldset>';
	}

	/**
	 * "Verified" toggle of a group.
	 *
	 * @param string $name    Input name.
	 * @param bool   $checked State.
	 * @param string $help    Help.
	 */
	public static function verify_toggle( $name, $checked, $help = '' ) {
		Admin::toggle( $name, __( 'Verified — I checked this myself', 'mr-tu-multilang-seo' ), $checked, '' !== $help ? $help : __( 'Only verified details appear on the website.', 'mr-tu-multilang-seo' ) );
	}

